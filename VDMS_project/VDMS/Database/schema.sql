CREATE DATABASE IF NOT EXISTS vdms_db CHARACTER SET utf8mb4;
USE vdms_db;

CREATE TABLE IF NOT EXISTS Users (
  Officer_ID       VARCHAR(20)  PRIMARY KEY,
  Full_Name        VARCHAR(100) NOT NULL,
  Role             VARCHAR(50)  NOT NULL,
  Email            VARCHAR(100) NOT NULL UNIQUE,
  Terminal_Station VARCHAR(30)  NOT NULL,
  Password_Hash    VARCHAR(100) NOT NULL            -- FIX 5: login needs a password (BCrypt hash)
);

CREATE TABLE IF NOT EXISTS Visitors (
  Visitor_ID    VARCHAR(20)  PRIMARY KEY,
  Full_Name     VARCHAR(100) NOT NULL,
  Phone_Number  VARCHAR(20)  NOT NULL,
  Email         VARCHAR(100) NOT NULL,
  QR_Code_Hash  VARCHAR(255) NULL UNIQUE,           -- FIX 4: generated by the app on first check-in
  INDEX idx_phone (Phone_Number)
);

-- FIX 6: guarantees unique Tracking IDs (no Random collisions)
CREATE TABLE IF NOT EXISTS Tracking_Sequence (
  Seq_ID     INT AUTO_INCREMENT PRIMARY KEY,
  Created_At DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Document_Logs (
  Tracking_ID          VARCHAR(30)  PRIMARY KEY,
  Visitor_ID           VARCHAR(20)  NOT NULL,
  Receiving_Officer_ID VARCHAR(20)  NULL,           -- FIX 3: NULL until an officer accepts the document
  Document_Type        VARCHAR(100) NOT NULL,
  Desk_Station         VARCHAR(30)  NULL,           -- desk QR code the visitor scanned
  Submission_Timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
  Current_Status       VARCHAR(50)  NOT NULL DEFAULT 'Pending',
  CONSTRAINT chk_status CHECK (Current_Status IN
    ('Pending','Received','In-Review','Ready for Pickup','Completed')),  -- FIX 7
  FOREIGN KEY (Visitor_ID) REFERENCES Visitors(Visitor_ID),
  FOREIGN KEY (Receiving_Officer_ID) REFERENCES Users(Officer_ID)
);

CREATE TABLE IF NOT EXISTS Notification_Logs (
  Notification_ID   INT AUTO_INCREMENT PRIMARY KEY,
  Tracking_ID       VARCHAR(30)  NOT NULL,
  Channel           VARCHAR(10)  NOT NULL CHECK (Channel IN ('SMS','Email')),
  Recipient_Contact VARCHAR(100) NOT NULL,
  Sent_Timestamp    DATETIME DEFAULT CURRENT_TIMESTAMP,
  Delivery_Status   VARCHAR(20)  NOT NULL,          -- Sent / Failed / Delivered
  Error_Detail      VARCHAR(255) NULL,              -- error text no longer overflows Delivery_Status
  FOREIGN KEY (Tracking_ID) REFERENCES Document_Logs(Tracking_ID)
);
